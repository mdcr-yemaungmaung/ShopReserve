  function t(key, params) {
    let text = translations[currentLang]?.[key] || translations['en']?.[key] || key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
      });
    }
    return text;
  }

  function setLang(lang) {
    currentLang = lang;
    try {
      localStorage.setItem('ezbooknow_lang', lang);
    } catch (e) {}
    if (typeof document !== 'undefined' && document.documentElement) {
      document.documentElement.lang = lang;
    }
    if (typeof document !== 'undefined' && document.body) {
      if (lang === 'mm') {
        document.body.style.fontFamily = "'Padauk', 'Noto Sans Myanmar', 'Inter', sans-serif";
      } else if (lang === 'ja') {
        document.body.style.fontFamily = "'Noto Sans JP', 'Hiragino Sans', 'Meiryo', 'Inter', sans-serif";
      } else {
        document.body.style.fontFamily = "'Inter', 'Padauk', sans-serif";
      }
    }
    // Dispatch event for re-render
    try {
      if (typeof window !== 'undefined' && window.dispatchEvent) {
        window.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
      }
    } catch (e) {}
  }

  function getLang() {
    return currentLang;
  }

  function formatMonth(monthIndex) {
    return t(`month_${monthIndex + 1}`);
  }

  function formatWeekday(dayIndex, short = false) {
    const dayKeys = ['sun', 'mon', 'tue', 'wed', 'thu', 'fri', 'sat'];
    const key = short ? `day_${dayKeys[dayIndex]}_short` : `day_${dayKeys[dayIndex]}`;
    return t(key);
  }

  function formatFullDate(isoDate) {
    if (!isoDate) return '';
    const parts = isoDate.split('-').map(n => parseInt(n, 10));
    const d = new Date(parts[0], parts[1] - 1, parts[2]);
    const weekday = formatWeekday(d.getDay());
    const month = formatMonth(d.getMonth());
    const day = String(d.getDate()).padStart(2, '0');
    return t('date_format_full', { weekday, month, day });
  }

  function formatMonthYear(year, monthIndex) {
    const month = formatMonth(monthIndex);
    return t('calendar_month_year', { month, year: String(year) });
  }

