  function t(key, params) {
    let text = translations[currentLang]?.[key] || translations['en']?.[key] || key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        text = text.replace(`{${k}}`, v);
      });
    }
    return text;
  }

  function setLang(lang) {
    currentLang = lang;
    try {
      localStorage.setItem('ezbooknow_lang', lang);
    } catch (e) {}
    if (document.documentElement) {
      document.documentElement.lang = lang;
    }
    if (document.body) {
      if (lang === 'mm') {
        document.body.style.fontFamily = "'Padauk', 'Inter', sans-serif";
      } else {
        document.body.style.fontFamily = "'Inter', 'Padauk', sans-serif";
      }
    }
    // Dispatch event for re-render
    try {
      window.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
    } catch (e) {}
  }

  function getLang() {
    return currentLang;
  }

  return { t, setLang, getLang };
