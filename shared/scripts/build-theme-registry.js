/* ============================================================
   EzBookNow — Build Theme Registries (shared/scripts/build-theme-registry.js)
   Each app owns its OWN design-system catalog. This script scans
   per-app theme folders and writes a per-app registry:

     user/design-systems/*.md   -> user/registry.json + user/registry-data.js
     shop/design-systems/*.md   -> shop/registry.json + shop/registry-data.js
     admin/design-systems/*.md  -> admin/registry.json + admin/registry-data.js

   registry-data.js embeds the same data as a script tag so the
   prototype also works when opened directly from disk (file://),
   where fetch() of local files is blocked by browsers.

   Node built-ins ONLY (fs, path). No package.json, no npm deps.
   Reuses the shared theme-engine for parsing + token compilation.

   Run: node shared/scripts/build-theme-registry.js
   ============================================================ */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rawEngine = require('../theme/theme-engine.js');
const ThemeEngine = globalThis.ThemeEngine || rawEngine.ThemeEngine || rawEngine.default || rawEngine;

const ROOT = path.resolve(__dirname, '..', '..');
const APPS = ['user', 'shop', 'admin'];

function slugify(name) {
  return String(name || '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

function buildApp(app) {
  const APP_DIR = path.join(ROOT, app);
  const THEMES_DIR = path.join(APP_DIR, 'design-systems');
  const OUT_FILE = path.join(APP_DIR, 'registry.json');
  const OUT_JS = path.join(APP_DIR, 'registry-data.js');

  if (!fs.existsSync(THEMES_DIR)) {
    console.error(`[theme-registry] ${app}: missing themes folder ${THEMES_DIR}. Skipping.`);
    return;
  }

  const files = fs.readdirSync(THEMES_DIR).filter(f => f.toLowerCase().endsWith('.md'));

  if (files.length === 0) {
    console.warn(`[theme-registry] ${app}: no .md theme files found in ${THEMES_DIR}. Writing empty registry.`);
  }

  const themes = [];

  for (const file of files) {
    const filePath = path.join(THEMES_DIR, file);
    const md = fs.readFileSync(filePath, 'utf8');
    const tokens = ThemeEngine.parseDesignDoc(md);

    if (!tokens) {
      console.warn(`[theme-registry] ${app}: SKIP ${file}: no valid YAML frontmatter (--- ... ---)`);
      continue;
    }

    const summary = ThemeEngine.summarize(tokens);
    const cssVars = ThemeEngine.tokensToCssVars(tokens);

    themes.push({
      id: slugify(tokens.name),
      file,
      name: tokens.name,
      primary: summary.primary,
      secondary: summary.secondary,
      hasCustomTypography: summary.hasCustomTypography,
      colors: tokens.colors,
      typography: tokens.typography,
      rounded: tokens.rounded,
      spacing: tokens.spacing,
      cssVars
    });

    console.log(`[theme-registry] ${app}: registered "${tokens.name}" from ${file}`);
  }

  const registry = {
    app,
    generatedAt: new Date().toISOString(),
    themeCount: themes.length,
    themes
  };

  fs.writeFileSync(OUT_FILE, JSON.stringify(registry, null, 2), 'utf8');
  console.log(`[theme-registry] ${app}: wrote ${OUT_FILE} (${themes.length} themes).`);

  // Also emit registry-data.js so the prototype works over file:// where
  // fetch() of local JSON is blocked. Script tags always load.
  const js = `/* Auto-generated by shared/scripts/build-theme-registry.js — do not edit. */\n` +
    `window.THEME_REGISTRY = ` + JSON.stringify(registry) + ';\n';
  fs.writeFileSync(OUT_JS, js, 'utf8');
  console.log(`[theme-registry] ${app}: wrote ${OUT_JS} (embedded, file:// friendly).`);
  return themes;
}

const allThemesMap = new Map();
for (const app of APPS) {
  const appThemes = buildApp(app);
  if (appThemes) {
    appThemes.forEach(t => {
      if (!allThemesMap.has(t.id)) {
        allThemesMap.set(t.id, t);
      }
    });
  }
}

// Build combined shared registry for the Enterprise Hub
const SHARED_DIR = path.join(ROOT, 'shared');
const SHARED_OUT_FILE = path.join(SHARED_DIR, 'registry.json');
const SHARED_OUT_JS = path.join(SHARED_DIR, 'registry-data.js');

const sharedThemes = Array.from(allThemesMap.values());
const sharedRegistry = {
  app: 'hub',
  generatedAt: new Date().toISOString(),
  themeCount: sharedThemes.length,
  themes: sharedThemes
};

fs.writeFileSync(SHARED_OUT_FILE, JSON.stringify(sharedRegistry, null, 2), 'utf8');
console.log(`[theme-registry] shared: wrote ${SHARED_OUT_FILE} (${sharedThemes.length} themes).`);

const sharedJs = `/* Auto-generated by shared/scripts/build-theme-registry.js — do not edit. */\n` +
  `window.THEME_REGISTRY = ` + JSON.stringify(sharedRegistry) + ';\n';
fs.writeFileSync(SHARED_OUT_JS, sharedJs, 'utf8');
console.log(`[theme-registry] shared: wrote ${SHARED_OUT_JS} (embedded, file:// friendly).`);